def test_docx_omits_deleted_rows_and_does_not_flatten_shifted_rows_as_columns(tmp_path):
    def row(properties, first, second):
        return f'<w:tr><w:trPr>{properties}</w:trPr><w:tc><w:p><w:r><w:t>{first}</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>{second}</w:t></w:r></w:p></w:tc></w:tr>'
    path = tmp_path / 'synthetic.docx'
    path.write_bytes(make_docx('<w:tbl>' + row('<w:del/>', 'Deleted', '9') + row('<w:gridBefore w:val="1"/>', 'Synthetic', '4') + '</w:tbl>'))
    assert document_parser.parse(path, document_parser.DOCX_TYPE)[0]['text'] == 'Synthetic\n4'
    path.write_bytes(make_docx('<w:tbl>' + row('<w:del/>', 'Deleted', '9') + row('', 'Synthetic', '4') + '</w:tbl>'))
    assert document_parser.parse(path, document_parser.DOCX_TYPE)[0]['text'] == 'Synthetic | 4'


def test_docx_rejects_entities_macros_and_archive_bombs(tmp_path):
    path = tmp_path / "bad.docx"
    path.write_bytes(make_docx('<w:p><w:r><w:t>Safe</w:t></w:r></w:p>', [("word/vbaProject.bin",b"synthetic")]))
    with pytest.raises(ValueError, match="invalid_docx_package"):
        document_parser.parse(path, document_parser.DOCX_TYPE)
    path.write_bytes(make_docx('', [("oversized.bin",b"x"*8_000_001)]))
    with pytest.raises(ValueError, match="unsafe_docx_entry"):
        document_parser.parse(path, document_parser.DOCX_TYPE)
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w") as archive:
        archive.writestr("[Content_Types].xml",f'<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Override PartName="/word/document.xml" ContentType="{document_parser.MAIN_TYPE}"/></Types>')
        archive.writestr("word/document.xml", '<!DOCTYPE x [<!ENTITY e "boom">]><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>&e;</w:t></w:r></w:p></w:body></w:document>')
    path.write_bytes(output.getvalue())
    with pytest.raises(Exception) as exc:
        document_parser.parse(path, document_parser.DOCX_TYPE)
    assert type(exc.value).__name__ == "DTDForbidden"


@pytest.mark.parametrize("media_type,format_name", [("image/jpeg","JPEG"), ("image/png","PNG")])
def test_image_ocr_and_preview_share_exif_orientation(tmp_path, monkeypatch, media_type, format_name):
    path = tmp_path / "synthetic-image"
    image = Image.new("RGB", (40,20), "white")
    for y in range(10):
        for x in range(10):
            image.putpixel((x,y),(255,0,0))
    exif = image.getexif(); exif[274] = 6
    image.save(path, format=format_name, exif=exif)
    captured=[]
    monkeypatch.setattr(document_parser, "ocr", lambda data: captured.append(data) or "Synthetic OCR")
    document_parser.parse(path, media_type)
    with Image.open(io.BytesIO(captured[0])) as ocr_image, Image.open(io.BytesIO(subprocess.run([sys.executable,"-m","app.document_preview",str(path),media_type,"1"],capture_output=True,check=True).stdout)) as preview:
        assert ocr_image.size == preview.size == (20,40)
        assert ocr_image.getpixel((15,5))[0] > 200
        assert ocr_image.tobytes() == preview.tobytes()
        assert 274 not in ocr_image.getexif()


