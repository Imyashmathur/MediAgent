def test_docx_segments_never_truncate_a_line(tmp_path, monkeypatch):
    monkeypatch.setattr(document_parser, 'MAX_PAGE_CHARS', 25)
    text = ['Test name: Synthetic', 'Observed value: 12345', 'Unit: mg']
    body = ''.join(f'<w:p><w:r><w:t>{line}</w:t></w:r></w:p>' for line in text)
    path = tmp_path / 'synthetic.docx'
    path.write_bytes(make_docx(body))
    segments = document_parser.parse(path, document_parser.DOCX_TYPE)
    assert '\n'.join(segment['text'] for segment in segments) == '\n'.join(text)
    assert all(len(segment['text']) <= 25 for segment in segments)
    assert any(segment['text'] == 'Observed value: 12345' for segment in segments)
    path.write_bytes(make_docx('<w:p><w:r><w:t>' + 'x' * 26 + '</w:t></w:r></w:p>'))
    with pytest.raises(ValueError, match='docx_line_limit'):
        document_parser.parse(path, document_parser.DOCX_TYPE)


