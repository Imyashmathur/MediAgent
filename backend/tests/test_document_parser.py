def test_vision_parser_subprocess_uses_real_http_contract_with_synthetic_service(tmp_path, monkeypatch):
    import base64
    import json
    import threading
    from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
    requests = []
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *args): pass
        def do_POST(self):
            body=json.loads(self.rfile.read(int(self.headers["Content-Length"])))
            requests.append((self.path,body))
            payload=json.dumps({"done":True,"done_reason":"stop","message":{"role":"assistant","content":json.dumps({"text":"Synthetic vision output","warnings":["Check original"]})}}).encode()
            self.send_response(200); self.send_header("Content-Type","application/json"); self.send_header("Content-Length",str(len(payload))); self.end_headers(); self.wfile.write(payload)
    server=ThreadingHTTPServer(("127.0.0.1",0),Handler)
    thread=threading.Thread(target=server.serve_forever,daemon=True); thread.start()
    path=tmp_path / "synthetic.pdf"
    with pymupdf.open() as pdf:
        pdf.new_page().insert_text((72,72),"Synthetic source")
        pdf.save(path)
    from app.parser_subprocess import run_document_parser
    for key, value in {"VISION_PROVIDER":"ollama","OLLAMA_BASE_URL":f"http://127.0.0.1:{server.server_port}","OLLAMA_VISION_MODEL":"synthetic-vision","OCR_PROVIDER":"disabled","PDF_OCR_MODE":"fallback"}.items():
        monkeypatch.setenv(key, value)
    try:
        result=run_document_parser([sys.executable,"-m","app.document_parser",str(path),"application/pdf","vision"],timeout=20)
    finally:
        server.shutdown(); server.server_close(); thread.join(timeout=5)
    output=json.loads(result.stdout)
    assert output["pages"][0]["vision_text"] == "Synthetic vision output"
    assert output["pages"][0]["vision_warnings"] == ["Check original"]
    assert output["processor_details"]["vision"] == {"provider":"ollama","model":"synthetic-vision","pages_processed":1,"truncated":False}
    assert requests[0][0] == "/api/chat"
    assert base64.b64decode(requests[0][1]["messages"][1]["images"][0]).startswith(b"\x89PNG\r\n\x1a\n")
